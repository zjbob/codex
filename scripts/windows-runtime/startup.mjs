import fs from 'node:fs';
import path from 'node:path';
import {spawn, spawnSync} from 'node:child_process';
import {hash, toolkitHash, writeNewJson} from './runtime.mjs';
const [binaryArg, output, expectedModel='gpt-6.1-sol']=process.argv.slice(2);
if(!binaryArg || !output)throw Error('Usage: node startup.mjs <codex.exe> <result.json> [expected-model]');
if(fs.existsSync(output))throw Error('Use a fresh result path');
const binary=fs.realpathSync(binaryArg);const binarySha256=hash(binary);
const toolkitSha256=toolkitHash();
fs.mkdirSync(path.dirname(path.resolve(output)),{recursive:true});
const child=spawn(binary,['app-server'],{windowsHide:true,stdio:['pipe','pipe','pipe']});
let pending='',stderr='',catalog,initialized=false,timedOut=false;
const send=x=>child.stdin.write(JSON.stringify(x)+'\n');
child.stderr.on('data',c=>stderr+=c);
child.stdout.on('data',c=>{pending+=c;let i;while((i=pending.indexOf('\n'))>=0){const line=pending.slice(0,i);pending=pending.slice(i+1);let m;try{m=JSON.parse(line)}catch{continue}if(m.id===1){initialized=!!m.result;send({method:'initialized',params:{}});send({id:2,method:'model/list',params:{includeHidden:true}});}if(m.id===2){catalog=m.result?.data;child.stdin.end();}}});
const timer=setTimeout(()=>{timedOut=true;if(process.platform==='win32')spawnSync('taskkill',['/PID',String(child.pid),'/T','/F'],{windowsHide:true});else child.kill()},30000);
send({id:1,method:'initialize',params:{clientInfo:{name:'local-runtime-verification',version:'1.0'},capabilities:{experimentalApi:true}}});
const exit=await new Promise(resolve=>{child.on('exit',resolve);child.on('error',e=>resolve(e.message));});clearTimeout(timer);
const models=catalog?.map(x=>x.model??x.id)??[];
const result={binary,binarySha256,toolkitSha256,expectedModel,codexHomeOverride:!!process.env.CODEX_HOME,exit,timedOut,initialized,models,sqliteError:/sqlite.{0,100}(error|fail)|migration.{0,100}(error|fail)|error.{0,100}(sqlite|migration)/i.test(stderr),stderr:stderr.slice(-4000)};
result.passed=toolkitHash()===toolkitSha256&&hash(binary)===binarySha256&&exit===0&&initialized&&models.includes(expectedModel)&&!result.sqliteError&&!timedOut;
writeNewJson(output,result);console.log(JSON.stringify(result,null,2));if(!result.passed)process.exitCode=1;
